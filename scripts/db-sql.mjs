#!/usr/bin/env node
/**
 * Combine every migration into one file to paste into the Supabase SQL editor.
 *
 *   npm run db:sql                                   a database with no lockdown
 *   node scripts/db-sql.mjs --with-lockdown          the RLS lockdown is in force
 *   node scripts/db-sql.mjs --with-lockdown --with-scoping
 *                                                    ...and hospital scoping is on
 *
 * The no-credential path. `npm run db:migrate` is better — it records what it
 * applied in the migration history, so the next run knows what is already
 * there — but it needs the database password. This needs nothing except a
 * browser already logged into the Supabase dashboard.
 *
 * WHY ALL OF THEM, NOT JUST THE RECENT ONES
 * Working out which migrations are outstanding requires connecting to the
 * database, which is the thing this path exists to avoid. Every migration in
 * this repository is idempotent — that is checked before anything is written,
 * and the check fails the command if it is not — so running the whole set is
 * safe whatever state the database is in. Re-running an applied migration
 * changes nothing; missing an unapplied one is a broken feature.
 *
 * NEVER WIDER THAN THE DATABASE IS NOW
 * Replaying old migrations recreates their "Allow all access" policies. The
 * combined file therefore starts with a guard that reads the database's own
 * state (app_private.rls_lockdown_state, app_private.access_policy_state) and
 * refuses to run — before changing anything — when the lockdown or hospital
 * scoping is in force but this file would not put it back.
 *
 * WHAT THIS DOES NOT DO
 * It does not write to `supabase_migrations.schema_migrations`. The CLI will
 * still think nothing has been applied, which is harmless precisely because
 * everything is re-runnable — but it means `npm run db:migrate` remains worth
 * running once when you have the password to hand.
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkMigrations, reportMigrations } from './check-migrations.mjs';

const DIR = 'supabase/migrations';
const OUT_DIR = 'supabase/.combined';
const OUT = join(OUT_DIR, 'all-migrations.sql');
export const LOCKDOWN = 'supabase/manual/20261019100000_rls_lockdown.sql';
export const SCOPING = 'supabase/manual/20261020100000_hospital_scoping.sql';

const rule = (char = '=') => char.repeat(76);

/** A hand-applied file's body, to run inside the combined transaction. */
export function innerSql(text) {
  const lines = String(text).split(/\r?\n/);
  // Everything after its own COMMIT (NOTIFY, read-only reports) is dropped:
  // the combined file notifies once, at the end.
  const commit = lines.findIndex((line) => /^\s*COMMIT\s*;\s*$/i.test(line));
  return (commit === -1 ? lines : lines.slice(0, commit))
    .filter((line) => !/^\s*(BEGIN|COMMIT)\s*;\s*$/i.test(line))
    .join('\n')
    .trimEnd();
}

/**
 * The guard at the top of the combined file: refuse to replay the migrations
 * into a database whose current protection this file would not put back.
 */
export function stateGuard({ withLockdown, withScoping }) {
  return [
    'DO $$',
    'BEGIN',
    ...(withLockdown ? [] : [
      "  IF to_regclass('app_private.rls_lockdown_state') IS NOT NULL",
      '     AND EXISTS (SELECT 1 FROM app_private.rls_lockdown_state WHERE in_force IS TRUE) THEN',
      "    RAISE EXCEPTION 'The RLS lockdown is in force on this database, and replaying the migrations would re-open it. Regenerate this file with: node scripts/db-sql.mjs --with-lockdown (nothing was changed).';",
      '  END IF;',
    ]),
    ...(withScoping ? [] : [
      "  IF to_regclass('app_private.access_policy_state') IS NOT NULL",
      '     AND EXISTS (SELECT 1 FROM app_private.access_policy_state WHERE hospital_scoped IS TRUE)',
      "     AND to_regprocedure('app_private.apply_hospital_scoping()') IS NULL THEN",
      "    RAISE EXCEPTION 'Hospital scoping is on but cannot be re-applied from the database. Regenerate with: node scripts/db-sql.mjs --with-lockdown --with-scoping (nothing was changed).';",
      '  END IF;',
    ]),
    '  NULL;',
    'END $$;',
  ].join('\n');
}

/**
 * Build the combined script. Pure, so the order is unit-tested:
 * BEGIN, guard, migrations, lockdown, scoping, COMMIT.
 */
export function buildCombinedSql({ migrations, lockdown = null, scoping = null, generatedAt = new Date() }) {
  if (scoping && !lockdown) throw new Error('--with-scoping needs --with-lockdown: hospital scoping sits on top of the lockdown.');
  const flags = `${lockdown ? ' --with-lockdown' : ''}${scoping ? ' --with-scoping' : ''}`;
  const parts = [
    `-- ${rule()}`,
    '-- ALL MIGRATIONS, COMBINED',
    '--',
    `-- Generated by \`node scripts/db-sql.mjs${flags}\` on ${generatedAt.toISOString()}.`,
    `-- ${migrations.length} migration${migrations.length === 1 ? '' : 's'}, in the order they must run.`,
    '--',
    '-- Every statement is idempotent, so this is safe to run against a database',
    '-- in any state: already-applied migrations change nothing, and anything',
    '-- outstanding is applied. Safe to run more than once.',
    '--',
    '-- Paste the whole file into the Supabase SQL editor and run it.',
    `-- ${rule()}`,
    '',
    'BEGIN;',
    '',
    stateGuard({ withLockdown: !!lockdown, withScoping: !!scoping }),
    '',
  ];
  // The scoping file comes later in this transaction, with the repository's
  // newest classification: the lockdown leaves the re-apply to it.
  if (scoping) parts.push("SET LOCAL app.hospital_scoping_follows = 'on';", '');

  for (const { file, sql } of migrations) {
    parts.push('', `-- ${rule('-')}`, `-- ${file}`, `-- ${rule('-')}`, '', String(sql).trimEnd(), '');
  }

  // --with-lockdown: for a database where the RLS lockdown is already in
  // force. Replaying the migrations recreates their "Allow all access"
  // policies, so the lockdown is re-applied before the same COMMIT — the data
  // is never open, not even between two statements. Its own BEGIN/COMMIT are
  // dropped so it joins this transaction. --with-scoping does the same for
  // hospital scoping, after the lockdown it narrows.
  if (lockdown) {
    parts.push('', `-- ${rule('-')}`, `-- ${LOCKDOWN} (re-applied: the lockdown is in force on this database)`, `-- ${rule('-')}`, '', innerSql(lockdown), '');
  }
  if (scoping) {
    parts.push('', `-- ${rule('-')}`, `-- ${SCOPING} (re-applied: hospital scoping is on for this database)`, `-- ${rule('-')}`, '', innerSql(scoping), '');
  }

  // One transaction: either the whole schema moves forward or none of it does,
  // so a failure cannot leave the database in a state nobody has seen.
  parts.push('', 'COMMIT;', '');
  parts.push("NOTIFY pgrst, 'reload schema';", '');
  return parts.join('\n');
}

function main(argv = process.argv) {
  // Refuse to build a paste-once file out of statements that cannot be re-run:
  // a failure halfway through the editor leaves the schema half-applied.
  const result = checkMigrations(DIR);
  if (!result.ok) {
    console.error('Not generating a combined file — some migrations are not safe to re-run:\n');
    reportMigrations(result);
    process.exit(1);
  }

  const files = readdirSync(DIR).filter(f => f.endsWith('.sql')).sort();
  if (!files.length) {
    console.error(`No migrations found in ${DIR}.`);
    process.exit(1);
  }

  const withLockdown = argv.includes('--with-lockdown');
  const withScoping = argv.includes('--with-scoping');
  if (withScoping && !withLockdown) {
    console.error('--with-scoping needs --with-lockdown too: hospital scoping sits on top of the lockdown.');
    process.exit(1);
  }

  const sql = buildCombinedSql({
    migrations: files.map((file) => ({ file, sql: readFileSync(join(DIR, file), 'utf8') })),
    lockdown: withLockdown ? readFileSync(LOCKDOWN, 'utf8') : null,
    scoping: withScoping ? readFileSync(SCOPING, 'utf8') : null,
  });

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT, sql, 'utf8');

  console.log('Combined migration written.\n');
  console.log(`  File:       ${OUT}`);
  console.log(`  Migrations: ${files.length}${withLockdown ? ' + RLS lockdown' : ''}${withScoping ? ' + hospital scoping' : ''}`);
  console.log(`  Lines:      ${sql.split('\n').length}\n`);
  for (const f of files) console.log(`    ${f}`);
  console.log('\nNext:');
  console.log('  1. Open the Supabase dashboard for this project → SQL Editor → New query.');
  console.log(`  2. Paste the whole contents of ${OUT}.`);
  console.log('  3. Run. It is wrapped in a transaction, so it either all applies or none does.');
  console.log('     If the database is locked down or hospital-scoped and this file was');
  console.log('     generated without that, it refuses to run and changes nothing.');
  console.log('\nOr, with the database password to hand, `npm run db:migrate` does the same thing');
  console.log('and records it in the migration history so future runs know what is already there.');
}

// Only when run directly, not when imported by tests.
const invoked = process.argv[1] ? resolve(process.argv[1]) : '';
if (invoked && resolve(fileURLToPath(import.meta.url)) === invoked) {
  main();
}
